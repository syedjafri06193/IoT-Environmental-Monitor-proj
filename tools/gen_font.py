#!/usr/bin/env python3
"""Generate firmware/src/font6x11.c from Pillow's built-in 6x11 bitmap font.

ASCII 0x20..0x7E are stored in order; the degree sign is stored at 0x7F so
the renderer can draw "°C" with a single-byte code ('\\x7f').

    python3 tools/gen_font.py > firmware/src/font6x11.c
"""
from PIL import ImageFont

W, H = 6, 11
CHARS = [chr(c) for c in range(0x20, 0x7F)] + ["°"]


def glyph_rows(font, ch):
    mask = font.getmask(ch)
    mw, mh = mask.size
    rows = []
    for y in range(H):
        bits = 0
        for x in range(W):
            on = x < mw and y < mh and mask.getpixel((x, y)) > 0
            bits |= (0x80 >> x) if on else 0
        rows.append(bits)
    return rows


def main():
    font = ImageFont.load_default_imagefont()
    print("/* Generated by tools/gen_font.py - do not edit. */")
    print('#include "font6x11.h"\n')
    print("const uint8_t font6x11[FONT_GLYPHS][FONT_H] = {")
    for ch in CHARS:
        rows = ", ".join("0x%02X" % r for r in glyph_rows(font, ch))
        label = "deg" if ch == "°" else ("'\\\\'" if ch == "\\" else repr(ch))
        print("    {%s}, /* %s */" % (rows, label))
    print("};")


if __name__ == "__main__":
    main()
